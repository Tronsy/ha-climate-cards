export const language = (hass?: HomeAssistant) => hass?.locale?.language ?? hass?.language ?? navigator.language ?? 'en';

export function localize(hass: HomeAssistant | undefined, key: string, n?: string | number): string {
  const dict = language(hass).toLowerCase().startsWith('de') ? de : en;
  const s = dict[key] ?? en[key] ?? key;
  return n === undefined ? s : s.replace('{n}', String(n));
}
